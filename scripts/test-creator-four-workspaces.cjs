"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const html=read("apps/video-workspace/production-system/index.html");
const app=read("apps/video-workspace/production-system/creator-os-app.js");
const shell=read("assets/gucc-shell.js");
const fixed=read("apps/video-workspace/legacy-prompt-studio-v6.html");
const publisher=read("apps/publishing-console/index.html");
const studioJs=read("apps/video-workspace/studio.js");
const stylesheet=read("apps/video-workspace/production-system/creator-four-workspaces.css");
for(const [i,key,label] of [["01","outcomes","项目中枢"],["02","creation","创作工作台"],["03","release","发布与复盘"],["04","knowledge","规则与资料"]])
  assert(html.includes('data-view="'+key+'"')&&html.includes('<b>'+i+'</b><span>'+label+'</span>'));
assert.equal((html.match(/data-view="(?:outcomes|creation|release|knowledge)"/g)||[]).length,4);
assert.equal((html.match(/class="view(?: active)?"/g)||[]).length,4,"Exactly four top-level Creator views");
assert(html.includes('data-creation-mode="fixed"')&&html.includes('data-creation-mode="dynamic"'));
assert(html.includes('data-creation-pane="fixed"')&&html.includes('data-creation-pane="dynamic"'));
assert(html.includes('id="fixedStudioFrame"')&&html.includes('legacy-prompt-studio-v6.html?embedded=1'));
assert(html.includes('id="publishConsoleFrame"')&&html.includes('publishing-console/?embedded=1'));
assert(html.includes('data-reference="core"')&&html.includes('data-reference="capabilities"')&&html.includes('data-reference="libraries"'));
assert(html.includes('id="projectRegistryDetails"')&&html.includes('id="projectCards"'));
assert(html.includes('id="projectPortfolio"')&&html.includes('id="outcomeCards"'));
assert(html.includes('id="dynamicCoverAssist"')&&html.includes('href="../../cover-generator/"'));
assert(fixed.includes('id="coverAssistant"')&&fixed.includes('href="../cover-generator/"'));
assert(studioJs.includes("$('coverAssistant').hidden=!aboutCover"));
assert(shell.includes("childRoutes.dashboard, childRoutes.workbench, childRoutes.distribution, childRoutes.governance"));
assert(!shell.includes("items: [childRoutes.fixed, childRoutes.workspace, childRoutes.cover, childRoutes.publish]"));
assert(app.includes('creator_deliverable_records?select=*&order=project_id.asc'));
assert(app.includes('Outcomes.summary(rows,v).done'));
assert(!app.includes("p.outcomeProgress="),"Never duplicate formal outcome truth into snapshot");
assert(app.includes('document.querySelectorAll("main.os-main > section.view")'));
assert(app.includes('data-creation-pane')&&app.includes('data-reference'));
assert(app.includes('e.data?.type')===false||app.includes('gucc:embedded-tool-height'));
assert(fixed.includes("creator-embed-shell.js?v=1")&&publisher.includes("creator-embed-shell.js?v=1"));
assert(stylesheet.includes("@media(max-width:760px)"));
console.log("Four creator workspace contracts passed: four navigation views, project registry, fixed+dynamic editor, publisher+review, governance, contextual cover, canonical outcome source.");
