"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.join(__dirname,"..");
const Outcomes=require("../apps/video-workspace/production-system/creator-os-outcomes.js");
const Orchestrator=require("../apps/video-workspace/production-system/orchestrator.js");
const html=fs.readFileSync(path.join(root,"apps/video-workspace/production-system/index.html"),"utf8");
const app=fs.readFileSync(path.join(root,"apps/video-workspace/production-system/creator-os-app.js"),"utf8");

const p=Orchestrator.createProject({projectId:"PROJECT-OUTCOMES-TEST",name:"独立成果进度",workflowMode:"six"});
p.videos=[{videoId:"FIONI",branch:"FIONI",name:"菲欧妮"},{videoId:"SEVERIAN",branch:"SEVERIAN",name:"赛维里安"}];
Orchestrator.buildWorkflow(p);
const [first,second]=Outcomes.videos(p);
assert.deepEqual([first.key,second.key],["FIONI","SEVERIAN"]);
assert.equal(Outcomes.summary(p,first).done,0);
assert.equal(Outcomes.summary(p,first).applicable,6);
assert.equal(Outcomes.summary(p,second).done,0);
const flowBefore=JSON.stringify(p.promptFlow);
const at="2026-10-17T12:00:00.000Z";
assert.throws(()=>Outcomes.update(p,first,"script",{status:"done",artifactRef:"SCRIPT_FINAL.md",verified:false}),/核实/);
assert.throws(()=>Outcomes.update(p,first,"script",{status:"done",artifactRef:"",verified:true}),/成果引用/);
assert.throws(()=>Outcomes.update(p,first,"script",{status:"done",artifactRef:"C:\\private\\script.md",verified:true}),/绝对路径/);
assert.throws(()=>Outcomes.update(p,first,"script",{status:"na",note:""}),/理由/);
const saved=Outcomes.update(p,first,"script",{status:"done",artifactRef:"script/SCRIPT_FINAL.md",verified:true,note:"口播稿检查通过"},at);
assert.equal(saved.verifiedAt,at);
assert.equal(Outcomes.summary(p,first).done,1);
assert.equal(Outcomes.summary(p,second).done,0,"Separate videos must never share completion");
assert.equal(JSON.stringify(p.promptFlow),flowBefore,"Manual outcome management must not mutate Prompt Flow");
assert.equal(p.history.at(-1).action,"OUTCOME_STATUS_UPDATED");
assert.equal(Outcomes.record(JSON.parse(JSON.stringify(p)),first,"script").source,"manual");
Outcomes.update(p,first,"subtitle",{status:"working",note:"等待录音"});
assert.equal(Outcomes.record(p,first,"subtitle").status,"working");
Outcomes.update(p,first,"cover",{status:"na",note:"该视频为仅音频版本"});
assert.equal(Outcomes.summary(p,first).applicable,5);
assert.equal(Outcomes.summary(p,first).percent,20);
Outcomes.update(p,first,"script",{status:"review",artifactRef:"script/SCRIPT_FINAL.md"});
assert.equal(Outcomes.record(p,first,"script").verifiedAt,null,"Downgrade clears verification");
const old=Orchestrator.createProject({projectId:"PROJECT-LEGACY-TEST",name:"旧流程",workflowMode:"six"});
Orchestrator.buildWorkflow(old);
const master=Outcomes.videos(old)[0];
const script=old.promptFlow.find(n=>n.sixOutcomeId==="script");
script.status="DONE";
assert.equal(Outcomes.record(old,master,"script").status,"review","AI receipt alone is not approval");
script.receiptEvidence={humanApproved:true,fileVerified:true,qualityVerified:true};
assert.equal(Outcomes.record(old,master,"script").status,"done");
Outcomes.update(old,master,"script",{status:"working"});
assert.equal(Outcomes.record(old,master,"script").status,"working","Manual record overrides inherited node state");
const noFlow=Orchestrator.createProject({projectId:"PROJECT-FIXED-ONLY",name:"只用固定 Prompt",workflowMode:"six"});
noFlow.promptFlow=[];
const fixedVideo=Outcomes.videos(noFlow)[0];
Outcomes.update(noFlow,fixedVideo,"visual",{status:"done",artifactRef:"visuals/scene01.mp4",verified:true});
assert.equal(Outcomes.summary(noFlow,fixedVideo).done,1);
assert(html.includes('id="view-outcomes"')&&html.includes('id="outcomeDialog"'));
assert(html.includes('creator-os-outcomes.js?v=1')&&html.includes('creator-os-outcomes.css?v=1'));
assert(app.includes("function renderOutcomeBoard()"));
console.log("Independent Creator outcome board passed: 6 slots, multi-video isolation, QC, legacy import, fixed-only projects.");
