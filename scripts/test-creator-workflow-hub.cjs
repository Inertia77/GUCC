const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Map = require('../assets/creator-workflow-map.js');
const Task = require('../assets/creator-ai-task-core.js');
const root = path.resolve(__dirname,'..');
const html = fs.readFileSync(path.join(root,'apps/video-workspace/index.html'),'utf8');
