-- Record real, user-entered publication receipts in the existing project event ledger.
-- This never sends a video to a platform and does not bypass the legacy publish-package gate.
create function gucc_private.creator_workspace_publication_receipts() returns trigger language plpgsql security definer set search_path='' as $$
declare e record; prior jsonb;
begin
 for e in select key,value from jsonb_each(coalesce(new.draft_data->'execution','{}')) loop
  prior=case when tg_op='UPDATE' then old.draft_data->'execution'->e.key else '{}'::jsonb end;
  if e.value->>'status'='已发布' and coalesce(e.value->>'postUrl','')~'^https://[^ /]+' and e.value is distinct from prior then
   insert into public.creator_project_events(project_id,owner_user_id,event_type,state,detail)
   values(new.project_id,new.owner_user_id,'VIDEO_PUBLICATION_RECORDED','PUBLISHED',jsonb_build_object('videoId',new.video_id,'platform',e.key,'postUrl',e.value->>'postUrl','postId',e.value->>'postId','source','human_publish_console','draftRevision',new.revision));
  end if;
 end loop;
 return new;
end $$;
revoke all on function gucc_private.creator_workspace_publication_receipts() from public,anon,authenticated;
create trigger creator_workspace_publication_receipts after insert or update on public.creator_os_publish_drafts
 for each row execute function gucc_private.creator_workspace_publication_receipts();
